## Uzmanlık Alanları ve Hizmet Verdiğimiz Sektörler

**Maden Sondajı**
Karot alma odaklı jeoloji ve maden arama operasyonları için wireline karotiyer sistemleri (BWL, HQ, NQ, PQ), emprenye elmas matkap, vidye matkap ve komple karot alma ekipmanları.

**Jeotermal ve Su Sondajı**
Derin kuyu sondajı için DTH çekiç, rotary ekipman, sondaj tijleri, kompresör bağlantıları ve çamur pompası çözümleri. DSİ izin süreçlerinde teknik dokümantasyon desteği.

**Jeoteknik Zemin Etütleri**
İnşaat, altyapı ve enerji projeleri için jeoteknik sondaj ekipmanı — küçük çaplı karotiyer sistemleri, SPT ekipmanları, örselenmemiş numune alma cihazları.

**Kaya Sondajı ve Patlatma Öncesi Delik Delme**
DTH çekiç, matkap uçu (bit) çeşitleri, kompresör hattı bağlantı elemanları.

**Endüstriyel Kuyu Bakım ve Onarım**
Mevcut kuyularda tıkanma, temizlik, yedek parça ihtiyacı için hızlı tedarik.

