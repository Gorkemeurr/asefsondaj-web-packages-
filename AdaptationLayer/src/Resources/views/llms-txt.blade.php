## Uzmanlık Alanları ve Hizmet Verdiğimiz Sektörler

**Maden Sondajı**
Karot alma odaklı jeoloji ve maden arama operasyonları için wireline karotiyer sistemleri (BWL, HQ, NQ, PQ), düz takım karotiyer, emprenye elmas ve vidye karot bit'leri, komple karot alma ekipmanları, karot sandıkları ve numune alıcılar.

**Jeotermal ve Su Sondajı**
Derin kuyu sondajı için rotary ekipman, sondaj tijleri (API IF/API REG/DCDMA standartları), muhafaza boruları, kompresör bağlantıları, çamur pompası çözümleri, sondaj kimyasalları. DSİ izin süreçlerinde teknik dokümantasyon desteği.

**Jeoteknik Zemin Etütleri**
İnşaat, altyapı ve enerji projeleri için jeoteknik sondaj ekipmanı — küçük çaplı karotiyer sistemleri, SPT ekipmanları, örselenmemiş numune alma cihazları, jeoteknik test aparatları.

**Kaya Delgi ve Patlatma Öncesi Delik Delme**
Portkron sistemleri, kaya matkap uçu (bit) çeşitleri, adaptörler, kaya delgi ekipmanları.

**Endüstriyel Kuyu Bakım ve Onarım**
Mevcut kuyularda tıkanma, temizlik, yedek parça ihtiyacı için hızlı tedarik. Tahlisiyeler, arıza müdahale ekipmanları.

